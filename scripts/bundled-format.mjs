/** Serialise the bundled food list as compact, readable JS. */
export function formatBundled(list, source){
  const row = e => `  { name: ${JSON.stringify(e.name)}, src: ${JSON.stringify(e.src)},\n    per100: [${e.per100.map(v=>+(+v).toFixed(3)).join(",")}] },`;
  return `/* Generated by ${source} on ${new Date().toISOString().slice(0,10)} — do not edit by hand.
   Common ingredients so searching works without a USDA key.
   Values per 100 g in NUTS order (see src/data.js). Entries marked "~" are approximate. */
export const BUNDLED = [
${list.map(row).join("\n")}
];
`;
}
